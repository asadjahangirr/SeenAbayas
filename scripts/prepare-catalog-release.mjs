// Produces a reviewable, one-time SQL Editor import. Never connects to a service.
import { readFile, writeFile, access } from "node:fs/promises";
import { z } from "zod";

const release = z.object({
  batch: z.string().regex(/^catalog-intake-[a-z0-9-]+$/),
  stockNote: z.string(),
  sizes: z.array(z.string().regex(/^\d{2}$/)).length(3),
  products: z.array(z.object({
    id: z.string().regex(/^design-[0-9]{2,4}$/),
    name: z.string().min(1).max(150),
    tone: z.string().min(1).max(80),
    pricePence: z.number().int().positive().nullable(),
    ready: z.boolean(),
    missing: z.string().optional(),
    description: z.string().min(1).max(2000),
    stock: z.record(z.string(), z.number().int().min(0)),
  })).min(1),
}).parse(JSON.parse(await readFile("assets/catalog-release-20261020.json", "utf8")));
const media = JSON.parse(await readFile("src/data/media.generated.json", "utf8"));
const ids = new Set();
for (const p of release.products) {
  if (ids.has(p.id)) throw new Error("Duplicate design in release.");
  ids.add(p.id);
  if (p.ready && !p.pricePence) throw new Error(`${p.id}: confirm the price before publication.`);
  if (Object.keys(p.stock).sort().join() !== [...release.sizes].sort().join()) throw new Error(`${p.id}: incomplete stock.`);
  p.photos = media.pieces.find(piece => piece.id === p.id)?.photos;
  if (!p.photos?.length) throw new Error(`${p.id}: missing photographs.`);
  for (const photo of p.photos) await access(`public${photo.src}`);
}
const payload = JSON.stringify(release);
if (payload.includes("$catalog$")) throw new Error("Unexpected SQL delimiter in content.");
const sql = `-- Generated by node scripts/prepare-catalog-release.mjs; review the source JSON.
-- Run ONCE in the existing Supabase SQL Editor AFTER deploying the new images.
-- Keeps existing product/variant IDs, orders, costs, categories and uploaded photos.
-- Client stock replaces sample quantities. Active reservations abort the ENTIRE import.
-- Unconfirmed photo/price matches remain private drafts. No payment settings change.
-- A repeated successful batch is a no-op, so it cannot reset later stock/admin edits.
begin;
create table if not exists seen_private.catalog_import_backups (
  batch text primary key,
  snapshot jsonb not null,
  created_at timestamptz not null default now()
);
alter table seen_private.catalog_import_backups enable row level security;
revoke all on seen_private.catalog_import_backups from public, anon, authenticated;

do $import$
declare
  release jsonb := $catalog$${payload}$catalog$::jsonb;
  item jsonb; extra jsonb; size_value text; pid uuid; vid uuid;
  photo_list jsonb; existing_photos jsonb; position_value integer;
begin
  lock table public.products, public.product_variants, seen_private.inventory in share row exclusive mode;
  if exists(select 1 from seen_private.catalog_import_backups where batch=release->>'batch') then
    raise notice 'This catalogue batch was already applied. No products or stock changed.';
    return;
  end if;
  if exists (
    select 1 from seen_private.inventory i
    join public.product_variants v on v.id=i.variant_id
    join public.products p on p.id=v.product_id
    where i.reserved>0 and p.design_reference in (select value->>'id' from jsonb_array_elements(release->'products'))
  ) then
    raise exception 'Catalogue update stopped: finish/cancel open test checkouts first, or refresh expired payment statuses in Admin > Orders. Reservations were not changed.';
  end if;
  insert into seen_private.catalog_import_backups(batch,snapshot)
  select release->>'batch',jsonb_build_object(
    'products',coalesce((select jsonb_agg(to_jsonb(p)) from public.products p where p.design_reference in (select value->>'id' from jsonb_array_elements(release->'products'))),'[]'::jsonb),
    'variants',coalesce((select jsonb_agg(to_jsonb(v)) from public.product_variants v join public.products p on p.id=v.product_id where p.design_reference in (select value->>'id' from jsonb_array_elements(release->'products'))),'[]'::jsonb),
    'inventory',coalesce((select jsonb_agg(to_jsonb(i)) from seen_private.inventory i join public.product_variants v on v.id=i.variant_id join public.products p on p.id=v.product_id where p.design_reference in (select value->>'id' from jsonb_array_elements(release->'products'))),'[]'::jsonb)
  );
  position_value:=0;
  for item in select value from jsonb_array_elements(release->'products') loop
    photo_list:=item->'photos';
    select id,photos into pid,existing_photos from public.products where design_reference=item->>'id';
    for extra in select value from jsonb_array_elements(coalesce(existing_photos,'[]'::jsonb)) loop
      if not exists(select 1 from jsonb_array_elements(photo_list) ph where ph->>'src'=extra->>'src') then
        photo_list:=photo_list||jsonb_build_array(extra);
      end if;
    end loop;
    if jsonb_array_length(photo_list)>12 then raise exception 'Too many combined photos for %. Review existing uploads first.',item->>'id'; end if;
    insert into public.products(design_reference,name,description,price_pence,status,details_confirmed,sort_order,photos,tone)
    values(item->>'id',item->>'name',item->>'description',(item->>'pricePence')::integer,'draft',false,position_value,photo_list,item->>'tone')
    on conflict(design_reference) do update set
      name=excluded.name,description=excluded.description,price_pence=coalesce(excluded.price_pence,public.products.price_pence),
      status='draft',details_confirmed=false,sort_order=excluded.sort_order,photos=excluded.photos,tone=excluded.tone
    returning id into pid;
    -- Retire old sample lengths without deleting IDs referenced by existing orders.
    update public.product_variants set active=false where product_id=pid;
    update seen_private.inventory set on_hand=0 where variant_id in (select id from public.product_variants where product_id=pid);
    for size_value in select value from jsonb_array_elements_text(release->'sizes') loop
      select id into vid from public.product_variants where product_id=pid and lower(size_label)=lower(size_value);
      if vid is null then
        insert into public.product_variants(product_id,size_label,sku,active,sort_order)
        values(pid,size_value,'SEEN-'||upper(item->>'id')||'-'||size_value,true,size_value::integer) returning id into vid;
      else
        update public.product_variants set active=true,sort_order=size_value::integer where id=vid;
      end if;
      insert into seen_private.inventory(variant_id,on_hand) values(vid,(item->'stock'->>size_value)::integer)
      on conflict(variant_id) do update set on_hand=excluded.on_hand;
    end loop;
    if (item->>'ready')::boolean then
      update public.products set status='published',details_confirmed=true where id=pid;
    end if;
    position_value:=position_value+1;
  end loop;
  insert into seen_private.admin_audit(action,entity,entity_id) values('import','catalog',release->>'batch');
end $import$;
commit;

-- SQL Editor verification only; exact quantities remain private to the backend.
select p.design_reference,p.name,p.price_pence,p.status,jsonb_agg(jsonb_build_object(
  'size',v.size_label,'on_hand',i.on_hand,'reserved',i.reserved
) order by v.sort_order) as sizes
from public.products p join public.product_variants v on v.product_id=p.id and v.active
join seen_private.inventory i on i.variant_id=v.id
where p.design_reference in (${release.products.map(p=>`'${p.id}'`).join(",")})
group by p.id order by p.sort_order;
`;
await writeFile("supabase/catalog-release-20261020.sql", sql);
console.log(`Prepared ${release.products.length} products: ${release.products.filter(p=>p.ready).length} ready, ${release.products.filter(p=>!p.ready).length} awaiting confirmed details. No database changes made.`);
